-- ============================================================================
-- THE MIRROR: schema (step 1)
--
-- Design goal: the quiz can change without a schema change.
--   * Questions are never columns. Each answer is one ROW keyed by a stable
--     question_key ('q1', 'aq3', 'tb1', ...). New/removed questions = new/absent rows.
--   * Every quiz_version stores a JSON snapshot of the questions as they were
--     worded at the time, so old responses stay readable after edits.
--   * Scores are rows too (dimension or archetype), so adding a dimension
--     needs no migration.
--   * Only the Edge Function (service role) can write. The browser never
--     touches these tables directly.
-- Run in the Supabase SQL editor (or as a migration).
-- ============================================================================

create extension if not exists pgcrypto;

-- One row per version of the quiz (bump quizVersion in the page when you change it)
create table if not exists public.quiz_versions (
  id          uuid primary key default gen_random_uuid(),
  quiz_slug   text not null,
  version     text not null,
  label       text,
  definition  jsonb not null default '{}'::jsonb,  -- snapshot: {dimensions, archetypes, questions[]}
  created_at  timestamptz not null default now(),
  unique (quiz_slug, version)
);

-- One row per person (email is the identity; lets you see someone retake it later)
create table if not exists public.respondents (
  id           uuid primary key default gen_random_uuid(),
  email        text not null,
  name         text,
  created_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create unique index if not exists respondents_email_key on public.respondents (lower(email));

-- One row per completed run of the quiz
create table if not exists public.responses (
  id                  uuid primary key default gen_random_uuid(),
  client_response_id  uuid not null unique,         -- generated by the page; makes retries idempotent
  respondent_id       uuid not null references public.respondents(id) on delete cascade,
  quiz_version_id     uuid not null references public.quiz_versions(id),
  source              text,                         -- 'assessment' or 'dev-mode-direct-scores'
  is_test             boolean not null default false,
  primary_archetype   text,
  supporting_archetype text,
  result              jsonb not null default '{}'::jsonb,  -- everything else computed (invitations, tensions, ...)
  schema_version      text,
  client_created_at   timestamptz,
  created_at          timestamptz not null default now()
);
create index if not exists responses_respondent_idx on public.responses (respondent_id);
create index if not exists responses_quiz_idx       on public.responses (quiz_version_id);
create index if not exists responses_created_idx    on public.responses (created_at desc);

-- One row per answered question
create table if not exists public.response_answers (
  response_id   uuid not null references public.responses(id) on delete cascade,
  question_key  text not null,
  section       text not null,       -- 'dimension' | 'archetype' | 'tiebreak' (free text, add your own)
  value_num     numeric,             -- raw numeric answer (e.g. Likert 1-5)
  scored_num    numeric,             -- value after reverse-scoring etc.
  value_json    jsonb,               -- non-numeric answers (e.g. {"first":"guardian","second":"explorer"})
  primary key (response_id, question_key)
);
create index if not exists response_answers_key_idx on public.response_answers (question_key);

-- One row per computed score
create table if not exists public.response_scores (
  response_id  uuid not null references public.responses(id) on delete cascade,
  kind         text not null,        -- 'dimension' | 'archetype'
  score_key    text not null,        -- 'viewOfGod', 'guardian', ...
  score        numeric,
  band         text,                 -- 'low' | 'mid' | 'high' (dimensions)
  primary key (response_id, kind, score_key)
);

-- ---------------------------------------------------------------------------
-- Admin check: a signed-in user whose app_metadata.role = 'admin'.
-- Grant it with:
--   update auth.users set raw_app_meta_data = coalesce(raw_app_meta_data,'{}'::jsonb) || '{"role":"admin"}'
--   where email = 'you@example.com';
-- (app_metadata can't be edited by the user, unlike user_metadata.)
-- ---------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean language sql stable as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin'
$$;

-- ---------------------------------------------------------------------------
-- Lock everything down. RLS on, no public policies, then admin read-only.
-- The Edge Function uses the service role, which bypasses RLS.
-- ---------------------------------------------------------------------------
alter table public.quiz_versions    enable row level security;
alter table public.respondents      enable row level security;
alter table public.responses        enable row level security;
alter table public.response_answers enable row level security;
alter table public.response_scores  enable row level security;

revoke all on public.quiz_versions, public.respondents, public.responses,
              public.response_answers, public.response_scores from anon, authenticated;
grant select on public.quiz_versions, public.respondents, public.responses,
                public.response_answers, public.response_scores to authenticated;

create policy admin_read on public.quiz_versions    for select to authenticated using (public.is_admin());
create policy admin_read on public.respondents      for select to authenticated using (public.is_admin());
create policy admin_read on public.responses        for select to authenticated using (public.is_admin());
create policy admin_read on public.response_answers for select to authenticated using (public.is_admin());
create policy admin_read on public.response_scores  for select to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------------
-- Single atomic write path, called only by the Edge Function.
-- Idempotent: resubmitting the same client_response_id returns the same id.
-- ---------------------------------------------------------------------------
create or replace function public.submit_mirror_response(p jsonb)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slug    text := p #>> '{quiz,slug}';
  v_version text := p #>> '{quiz,version}';
  v_quiz    uuid;
  v_person  uuid;
  v_resp    uuid;
  v_client  uuid := (p #>> '{response,clientResponseId}')::uuid;
begin
  -- quiz version: first submission of a new version registers its snapshot
  insert into quiz_versions (quiz_slug, version, definition)
  values (v_slug, v_version, coalesce(p #> '{quiz,definition}', '{}'::jsonb))
  on conflict (quiz_slug, version) do nothing;
  select id into v_quiz from quiz_versions where quiz_slug = v_slug and version = v_version;

  -- person
  insert into respondents (email, name)
  values (lower(trim(p #>> '{respondent,email}')), nullif(trim(p #>> '{respondent,name}'), ''))
  on conflict (lower(email)) do update
    set name = coalesce(excluded.name, respondents.name), last_seen_at = now()
  returning id into v_person;

  -- response (do nothing if this exact response was already stored)
  insert into responses (client_response_id, respondent_id, quiz_version_id, source, is_test,
                         primary_archetype, supporting_archetype, result, schema_version, client_created_at)
  values (v_client, v_person, v_quiz,
          p #>> '{response,source}',
          coalesce(p #>> '{response,source}', '') like 'dev-mode%',
          p #>> '{response,primaryArchetype}',
          p #>> '{response,supportingArchetype}',
          coalesce(p #> '{response,result}', '{}'::jsonb),
          p #>> '{response,schemaVersion}',
          nullif(p #>> '{response,createdAt}', '')::timestamptz)
  on conflict (client_response_id) do nothing
  returning id into v_resp;

  if v_resp is null then
    select id into v_resp from responses where client_response_id = v_client;
    return v_resp;
  end if;

  insert into response_answers (response_id, question_key, section, value_num, scored_num, value_json)
  select v_resp, a ->> 'key', a ->> 'section',
         (a ->> 'value_num')::numeric, (a ->> 'scored_num')::numeric,
         nullif(a -> 'value_json', 'null'::jsonb)
  from jsonb_array_elements(coalesce(p -> 'answers', '[]'::jsonb)) a;

  insert into response_scores (response_id, kind, score_key, score, band)
  select v_resp, s ->> 'kind', s ->> 'key', (s ->> 'score')::numeric, s ->> 'band'
  from jsonb_array_elements(coalesce(p -> 'scores', '[]'::jsonb)) s;

  return v_resp;
end;
$$;

revoke all on function public.submit_mirror_response(jsonb) from public, anon, authenticated;
grant execute on function public.submit_mirror_response(jsonb) to service_role;
